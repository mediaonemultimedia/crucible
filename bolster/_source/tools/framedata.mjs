/* Frame data for every fighter, straight from src/fighters/ (so it can't
   drift from the game): startup / active / recovery in ticks (60 = 1 s),
   damage, reach (world units ×1000 from his middle, including any ground
   the move covers before its hit), the frame advantage on hit and on block,
   and the projectiles. Prints Markdown.

     node tools/framedata.mjs > docs/FRAMES.md                              */
import { FIGHTERS, ROSTER, frameData, reachOf, dashOf, MAX_METER } from '../src/fighters/index.js';

const NAMES = { light: 'Light (O)', heavy: 'Heavy (P)', lowLight: 'Low (S+O)', airLight: 'Jump light', airHeavy: 'Jump heavy', signature: 'Signature (S+P)', special: 'Special (Space)' };
const sign = (n) => (n > 0 ? `+${n}` : `${n}`);
const out = [];
out.push('# Pillow Fight — frame data', '');
out.push('Generated by `node tools/framedata.mjs` from `src/fighters/index.js`. Ticks are 1/60 s. Reach is in sim units (1000 = one world unit, 9 cm at plush scale) from the fighter\'s middle, counting the ground a move covers before it hits (the heavy\'s lunge). Advantage is the attacker\'s, from the last active frame, ignoring hit-pause (it stops both sides alike); a knockdown is marked KD.', '');
const [df, db] = [dashOf().f, dashOf().b];
out.push(`Every fighter: forward dash (double-tap forward) ${df[0]} ticks, ${Math.round(df[0] * df[1] * 0.85)} units; backdash (double-tap back) ${db[0]} ticks, ${Math.round(db[0] * db[1] * 0.85)} units (approximate: the last ticks ease off).`, '');
for (const id of ROSTER) {
  const F = FIGHTERS[id];
  out.push(`## ${F.name} — ${F.animal} (STUFFING ${F.health}, walk ${F.walkF}/${F.walkB})`, '');
  out.push('| Move | Startup | Active | Recovery | Damage | Reach | On hit | On block | Notes |', '|---|---|---|---|---|---|---|---|---|');
  for (const key of ['light', 'heavy', 'lowLight', 'airLight', 'airHeavy', 'signature', 'special']) {
    const m = F.moves[key];
    const fd = frameData(m);
    const h = m.hits[m.hits.length - 1];
    const dmg = m.hits.length ? m.hits.reduce((s, x) => s + x.dmg, 0) : m.spawn.reduce((s, x) => s + x.proj.dmg, 0);
    const reach = m.spawn.length ? 'shot' : m.grab ? `grab ${m.grab.range}` : m.track ? 'tracks' : reachOf(m);
    let onHit = '—', onBlock = '—';
    if (h && !m.air && !h.auto && !h.whiff) {
      onHit = h.kd ? 'KD' : sign(h.hitstun - fd.recovery);
      onBlock = sign(h.blockstun - fd.recovery);
    }
    const notes = [];
    if (m.motion.some((mo) => mo.vx > 0)) notes.push(`lunge ${m.motion.filter((mo) => mo.vx > 0).map((mo) => `${mo.vx}×${mo.to - mo.from + 1}`).join(', ')}`);
    if (m.ext) notes.push(`limb hurt box out to ${m.ext.x1}, frames ${m.ext.from}–${m.ext.to}`);
    if (m.cancel) notes.push('cancels into heavy / signature / special on contact');
    if (m.low) notes.push('low');
    if (h && h.level === 'high') notes.push('overhead');
    if (m.invuln) notes.push(`invulnerable vs ${m.invuln.vs} ${m.invuln.from}–${m.invuln.to}`);
    if (key === 'special') notes.push(`needs a full meter (${MAX_METER})`);
    if (m.spawn.length) {
      const P = m.spawn[0].proj;
      notes.push(`${m.spawn.length > 1 ? `${m.spawn.length} shots` : 'one on screen at a time'}; speed ${P.vx}/tick, at height ${P.y}, ${P.dmg} dmg, chip ${P.chip} on block`);
    }
    out.push(`| ${NAMES[key]} — ${key === 'signature' ? F.signatureName : key === 'special' ? F.specialName : ''} | ${fd.startup} | ${fd.active} | ${fd.recovery} | ${dmg} | ${reach} | ${onHit} | ${onBlock} | ${notes.join('; ')} |`.replace(' —  |', ' |'));
  }
  out.push('');
}
console.log(out.join('\n'));
