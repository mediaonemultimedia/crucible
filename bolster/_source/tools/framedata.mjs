/* Frame data for every fighter, straight from src/fighters/ (so it can't
   drift from the game): startup / active / recovery in ticks (60 = 1 s),
   damage, reach (world units ×1000 from his middle, including any ground
   the move covers before its hit), the frame advantage on hit and on block,
   and the projectiles; the combat rules (block, throw, counter, chains,
   scaling); and each fighter's bread-and-butter combos, run in the sim to
   get their real damage. Prints Markdown.

     node tools/framedata.mjs > docs/FRAMES.md                              */
import { FIGHTERS, ROSTER, frameData, reachOf, dashOf, MAX_METER } from '../src/fighters/index.js';
import { createMatch, stepInPlace, TECH, LOCK, CANCEL, THROW_GAP, KO_SEQ, KO_FINAL } from '../src/sim/sim.js';
import { LIGHT, HEAVY, DOWN } from '../src/sim/input.js';

const NAMES = { light: 'Light (O)', heavy: 'Heavy (P)', lowLight: 'Low (S+O)', airLight: 'Jump light', airHeavy: 'Jump heavy', dive: 'Dive slam (air S+P)', throw: 'Throw (O+P)', signature: 'Signature (S+P)', special: 'Special (Space)' };
const BTN = { light: LIGHT, heavy: HEAVY, lowLight: DOWN | LIGHT, signature: DOWN | HEAVY };
const verdict = (adv) => (adv >= -2 ? 'safe' : adv >= -5 ? 'unsafe (close)' : 'punishable');

/* a combo, run in the sim like a player would (each press as the last hit lands) */
function runCombo(a, b, seq) {
  const r = FIGHTERS[a].moves.light.hits[0].box, reach = r.x + r.w;
  const d = Math.max(((FIGHTERS[a].push.w + FIGHTERS[b].push.w) >> 1) + 50, reach + FIGHTERS[b].hurt.stand.x + FIGHTERS[b].hurt.stand.w - 450);
  const st = createMatch({ p1: a, p2: b, seed: 3 });
  st.phase = 'fight'; st.f[0].x = -d >> 1; st.f[1].x = d >> 1;
  let i = 0, last = 0;
  const hits = [];
  for (let t = 0; t < 120; t++) {
    const f = st.f[0];
    let m = 0;
    if (i === 0) m = BTN[seq[i++]];
    else if (i < seq.length && f.act === 'attack' && f.hm && !last) {
      const mv = FIGHTERS[f.id].moves[f.mv];
      if (f.mv === seq[i - 1] && f.t > mv.hits[mv.hits.length - 1].to) m = BTN[seq[i++]];
    }
    last = m;
    stepInPlace(st, m, 0);
    for (const e of st.ev) if (e.k === 'hit' && e.p === 0) hits.push(e);
  }
  const ok = hits.length === seq.length && hits.every((e, j) => e.n === j + 1);
  return { ok, dmg: hits.reduce((s, e) => s + e.dmg, 0), amp: hits.length && hits[hits.length - 1].amp, meter: st.f[0].meter };
}
const BNB = {
  kevalanche: [['light', 'light', 'heavy'], ['lowLight', 'signature'], ['light', 'heavy']],
  rubberta: [['light', 'light', 'heavy'], ['lowLight', 'signature'], ['light', 'heavy']],
  johnny: [['light', 'light', 'heavy'], ['light', 'heavy']],
  sumaura: [['light', 'light', 'heavy'], ['lowLight', 'signature'], ['light', 'heavy']],
  k8e: [['light', 'light', 'heavy'], ['light', 'heavy']],
  sebas: [['light', 'light', 'heavy'], ['lowLight', 'signature'], ['light', 'heavy']],
  zach: [['light', 'light', 'heavy'], ['light', 'heavy']],
};
const SHORT = { light: 'O', heavy: 'P', lowLight: 'S+O', signature: 'S+P' };
const sign = (n) => (n > 0 ? `+${n}` : `${n}`);
const out = [];
out.push('# Pillow Fight — frame data', '');
out.push('Generated by `node tools/framedata.mjs` from `src/fighters/index.js`. Ticks are 1/60 s. Reach is in sim units (1000 = one world unit, 9 cm at plush scale) from the fighter\'s middle, counting the ground a move covers before it hits (the heavy\'s lunge). Advantage is the attacker\'s, from the last active frame, ignoring hit-pause (it stops both sides alike); a knockdown is marked KD.', '');
const [df, db] = [dashOf().f, dashOf().b];
out.push('## Combat rules', '',
  '- **Block is E.** Standing E blocks high and mid; S+E (crouching) blocks low and mid; overheads (jump attacks, the dive slam, Sky Neck, the Royal Squash) need a standing block. Holding back only walks away. Blocking holds you in place (no walking, jumping or dashing); every blocked hit pushes both fighters apart (the blocker 1.5× the hit\'s push, the attacker half of it — all of it in the corner). Only signatures, specials and shots chip.',
  `- **Throw is O+P together** (pressed within ${THROW_GAP} ticks of each other), at close range (touching + 520): startup 4, active 4–6, 30 ticks if it whiffs. It beats a blocker; it can't grab anyone in the air, knocked down, or still in hit/block stun. **Tech** it with O+P inside the first ${TECH} ticks of the hold: both are pushed apart, no damage. The toss lands at frame 24 of the hold (a knockdown).`,
  '- **Counter-hit:** hitting someone in their move\'s startup does 125% damage and +8 ticks of hitstun (a COUNTER pop).',
  `- **Chains:** on contact (hit or block), inside the cancel window (up to ${CANCEL} ticks after the last active frame): light → light (after its active frames) / heavy / S+P / special; low → light / heavy / S+P; heavy → S+P, or the special on a full meter. Three lights in a string lock lights out for ${LOCK} ticks.`,
  '- **Amplified finisher:** a heavy / signature / special cancelled into out of a chain, landing on someone still in hitstun, does 132% (one link) or 144% (two or more), a hard knockdown, and builds +90 / +130 meter. AMPLIFIED! on the HUD.',
  '- **Scaling:** the first three hits of a combo are full damage, then −15% a hit (to 45%; a special\'s hits not below 80%). The same light landing again within 2 s does 85%, 70%, 55%.',
  '- **Whiffs:** a heavy that touches nothing adds 6 ticks to its recovery.',
  `- **K.O.:** a ${KO_SEQ.freeze}-tick freeze, then the launch at 25% speed for ${KO_SEQ.slow} ticks and back to full over ${KO_SEQ.ramp}, a bounce, the banner at tick ${KO_SEQ.banner} (${KO_SEQ.len} ticks in all); the match-winning K.O.: ${KO_FINAL.slow} slow ticks, ${KO_FINAL.len} in all, higher.`, '');
out.push(`Every fighter: forward dash (double-tap forward) ${df[0]} ticks, ${Math.round(df[0] * df[1] * 0.85)} units; backdash (double-tap back) ${db[0]} ticks, ${Math.round(db[0] * db[1] * 0.85)} units (approximate: the last ticks ease off).`, '');
for (const id of ROSTER) {
  const F = FIGHTERS[id];
  out.push(`## ${F.name} — ${F.animal} (STUFFING ${F.health}, walk ${F.walkF}/${F.walkB})`, '');
  out.push('| Move | Startup | Active | Recovery | Damage | Reach | On hit | On block | Notes |', '|---|---|---|---|---|---|---|---|---|');
  for (const key of ['light', 'heavy', 'lowLight', 'airLight', 'airHeavy', 'dive', 'throw', 'signature', 'special']) {
    const m = F.moves[key];
    const fd = frameData(m);
    const notes0 = [];
    const h = m.hits[m.hits.length - 1];
    const dmg = m.hits.reduce((s, x) => s + x.dmg, 0) + m.spawn.reduce((s, x) => s + x.proj.dmg, 0);
    const reach = m.spawn.length ? 'shot' : m.grab ? (m.grab.throw ? `grab touch+${m.grab.near}` : `grab ${m.grab.range}`) : m.track ? 'tracks' : key === 'dive' ? 'below' : reachOf(m);
    let onHit = '—', onBlock = '—';
    if (h && !m.air && !h.auto && !h.whiff) {
      onHit = h.kd ? 'KD' : sign(h.hitstun - fd.recovery);
      onBlock = `${sign(h.blockstun - fd.recovery)} ${verdict(h.blockstun - fd.recovery)}`;
    }
    if (key === 'dive') { onHit = sign(m.hits[0].hitstun - F.moves.diveLand.impact); onBlock = `${F.moves.diveLand.total} lag on landing: punishable`; }
    if (key === 'throw') { const H = F.moves.throwHold.hits[0]; onHit = 'KD'; onBlock = 'unblockable'; notes0.push(`${H.dmg} damage; tech window ${TECH}`); }
    const notes = notes0.splice(0);
    if (m.motion.some((mo) => mo.vx > 0)) notes.push(`lunge ${m.motion.filter((mo) => mo.vx > 0).map((mo) => `${mo.vx}×${mo.to - mo.from + 1}`).join(', ')}`);
    if (m.ext) notes.push(`limb hurt box out to ${m.ext.x1}, frames ${m.ext.from}–${m.ext.to}`);
    if (m.cancel === 1) notes.push('chains into light / heavy / signature / special on contact');
    if (m.cancel === 2) notes.push('cancels into signature (or special) on contact');
    if (m.whiffLag) notes.push(`+${m.whiffLag} recovery on a whiff`);
    if (m.low) notes.push('low');
    if (h && h.level === 'high') notes.push('overhead');
    if (m.invuln) notes.push(`invulnerable vs ${m.invuln.vs} ${m.invuln.from}–${m.invuln.to}`);
    if (key === 'special') notes.push(`needs a full meter (${MAX_METER})`);
    if (m.spawn.length) {
      const P = m.spawn[0].proj;
      notes.push(`${key === 'special' ? `${m.spawn.length} shot${m.spawn.length > 1 ? 's' : ''} (${P.kind}, ${P.level})` : 'one on screen at a time'}; speed ${P.vx}/tick, at height ${P.y}, ${P.dmg} dmg, chip ${P.chip} on block`);
    }
    const dm = key === 'throw' ? F.moves.throwHold.hits[0].dmg : key === 'dive' ? `${dmg} (+${F.moves.diveLand.hits[0].dmg} shockwave)` : dmg;
    out.push(`| ${NAMES[key]} — ${key === 'signature' ? F.signatureName : key === 'special' ? F.specialName : key === 'dive' ? F.diveName : key === 'throw' ? F.throwName : ''} | ${fd.startup} | ${key === 'dive' ? 'to the floor' : fd.active} | ${key === 'dive' ? 'landing' : fd.recovery} | ${dm} | ${reach} | ${onHit} | ${onBlock} | ${notes.join('; ')} |`.replace(' —  |', ' |'));
  }
  out.push('', `**Bread and butter** (run in the sim on Kevalanche, from just inside the light's reach; every one a true combo):`, '');
  for (const seq of BNB[id]) {
    const r = runCombo(id, 'kevalanche', seq);
    out.push(`- ${seq.map((k) => SHORT[k]).join(' → ')}: ${r.ok ? `${seq.length} hits, ${r.dmg} damage${r.amp ? ', amplified finisher' : ''}, ${r.meter} meter` : 'does NOT combo'}`);
  }
  out.push('');
}
console.log(out.join('\n'));
